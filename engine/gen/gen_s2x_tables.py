#!/usr/bin/env python3
"""Generates src/dvbs2x_tables.h: what the DVB-S2X (ETSI EN 302 307-2) MODCODs
need on top of DVB-S2, taken from the tables of the dvbrx receiver
(libdvbrx/src), which were themselves measured on GNU Radio gr-dtv's
transmitter and gr-dvbs2rx (Copyright Free Software Foundation, Inc. / Ron
Economos; Igor Freire):
- for each MODCOD (VL-SNR excepted): PLS code, constellation (point of each
  bit label, normalised to unit mean power) and bit interleaver column order;
- BCH / LDPC parameters of the S2X code rates;
- LDPC parity address tables (EN 302 307-2 annexes), in the dvb_fec format:
  for each group of 360 information bits, the count then the addresses.

usage: gen_s2x_tables.py <dvbrx/libdvbrx/src> > src/dvbs2x_tables.h
"""
import math
import os
import re
import sys

src = sys.argv[1]
const = open(os.path.join(src, "const_tables.h")).read()
fec = open(os.path.join(src, "fec_table.h")).read()
ldpc = open(os.path.join(src, "ldpc_tables.h")).read()

# ---- MODCODs -------------------------------------------------------------------
row_re = re.compile(r'\{ 0x([0-9a-f]{2}), "(\w+)", "(\w+)", (\d), (\d), \{ ([-\d, ]+) \},\s*\{ (\{.*?\}) \} \},',
                    re.S)
modcods = []
for m in row_re.finditer(const):
    pls = int(m.group(1), 16)
    if pls < 0x80:
        continue
    name, rate, short, bits = m.group(2), m.group(3), int(m.group(4)), int(m.group(5))
    order = [int(v) for v in m.group(6).split(",")]
    pts = [complex(float(a), float(b)) for a, b in
           re.findall(r"\{ ([-\d.e]+)f, ([-\d.e]+)f \}", m.group(7))]
    assert len(pts) == 1 << bits, (name, rate, len(pts))
    p = math.sqrt(sum(abs(z) ** 2 for z in pts) / len(pts))
    pts = [z / p for z in pts]
    num, den = (int(v) for v in rate.split("_"))
    modcods.append((pls, name, num, den, short, bits, order, pts))

# ---- BCH / LDPC parameters -------------------------------------------------------
def fec_rows(label):
    body = re.search(r"fec_%s\[\] = \{(.*?)\};" % label, fec, re.S).group(1)
    return {r: (int(k), int(n), int(t)) for r, k, n, t in
            re.findall(r'\{ "(\w+)", (\d+), (\d+), (\d+) \}', body)}


fec_n, fec_s = fec_rows("normal"), fec_rows("short")
S2_RATES = {"1_4", "1_3", "2_5", "1_2", "3_5", "2_3", "3_4", "4_5", "5_6", "8_9", "9_10"}
# the S2X short 2/3 and 3/5 are the DVB-S2 codes, already in dvb_fec
needed = sorted({(f"{num}_{den}", short) for _, _, num, den, short, _, _, _ in modcods
                 if f"{num}_{den}" not in S2_RATES})

# ---- LDPC tables -------------------------------------------------------------------
tables = {}
for m in re.finditer(r"static const uint16_t (\w+)_(DEG|LEN|POS)\[\] = \{(.*?)\};", ldpc, re.S):
    tables.setdefault(m.group(1), {})[m.group(2)] = [int(v) for v in re.findall(r"\d+", m.group(3))]
for m in re.finditer(r"static const struct ldpc_table (\w+) = \{ (\d+), (\d+), (\d+),", ldpc):
    tables[m.group(1)]["NK"] = (int(m.group(3)), int(m.group(4)))
maps = {}
for label in ("normal", "short"):
    body = re.search(r"ldpc_map_%s\[\] = \{(.*?)\};" % label, ldpc, re.S).group(1)
    maps[label] = dict(re.findall(r'\{ "(\w+)", &(\w+) \}', body))


def rows_of(t):
    """count + addresses for each group of 360 information bits"""
    out, pos = [], 0
    for deg, n in zip(t["DEG"], t["LEN"]):
        for _ in range(n):
            out.append([deg] + t["POS"][pos:pos + deg])
            pos += deg
    assert pos == len(t["POS"])
    return out


print("/* SPDX-License-Identifier: GPL-3.0-or-later")
print(" * Generated by gen/gen_s2x_tables.py from the dvbrx receiver's tables (themselves from")
print(" * GNU Radio gr-dtv and gr-dvbs2rx, Copyright Free Software Foundation, Inc. / Ron Economos;")
print(" * Igor Freire): DVB-S2X (ETSI EN 302 307-2) MODCODs, VL-SNR excepted. */")
print("#ifndef DVBTX_DVBS2X_TABLES_H\n#define DVBTX_DVBS2X_TABLES_H\n\n#include <stdint.h>\n")

print("/* BCH / LDPC parameters of the DVB-S2X code rates */")
print("static const struct dvbs2x_fec_row { uint8_t num, den, short_frame; uint16_t kbch, kldpc, nparity; }"
      " dvbs2x_fec[] = {")
for rate, short in needed:
    k, n, t = (fec_s if short else fec_n)[rate]
    num, den = rate.split("_")
    nparity = n - k
    assert nparity == (168 if short else 16 * t), (rate, short, nparity, t)
    print(f"    {{ {num}, {den}, {short}, {k}, {n}, {nparity} }},")
print("};\n")

print("#ifdef DVBT2_TABLES_LDPC")
descs = []
for rate, short in needed:
    tname = maps["short" if short else "normal"][rate]
    t = tables[tname]
    k = (fec_s if short else fec_n)[rate][1]
    assert t["NK"][1] == k, (rate, short, t["NK"], k)
    rows = rows_of(t)
    flat = [v for r in rows for v in r]
    cname = f"dvbs2x_ldpc_tab_{rate}{'s' if short else 'n'}"
    print(f"static const uint16_t {cname}[{len(flat)}] = {{")
    for i in range(0, len(flat), 16):
        print("    " + ", ".join(str(v) for v in flat[i:i + 16]) + ",")
    print("};")
    num, den = rate.split("_")
    descs.append(f"    {{ {short}, {num}, {den}, 2, {len(rows)}, {cname} }},")
print("/* variant 2: DVB-S2(X) only */")
print("static const struct dvb_ldpc_code_desc dvbs2x_ldpc_codes[] = {")
print("\n".join(descs))
print("};")
print("#endif\n")

print("/* MODCODs: PLS code (pilot bit 0), bits per symbol, code rate, frame size, bit interleaver")
print(" * column order (codeword bit order[b] * rows + j is bit b, MSB first, of the label of")
print(" * symbol j; -1: no interleaving), points by label (unit mean power) */")
print("static const struct dvbs2x_modcod { uint8_t pls, bits, num, den, short_frame; const char *name;")
print("                                     int8_t order[8]; float pts[256][2]; } dvbs2x_modcods[] = {")
for pls, name, num, den, short, bits, order, pts in modcods:
    o = ", ".join(str(v) for v in order)
    p = ", ".join(f"{{ {z.real:.9e}f, {z.imag:.9e}f }}" for z in pts)
    print(f'    {{ 0x{pls:02x}, {bits}, {num}, {den}, {short}, "{name}", {{ {o} }},\n      {{ {p} }} }},')
print("};\n\n#endif")
