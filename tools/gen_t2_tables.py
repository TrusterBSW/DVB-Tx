"""Extract the large DVB-S2/T2 tables from the GNU Radio gr-dtv sources into a C header.

usage: gen_t2_tables.py <gr-dtv source dir (containing lib/dvb and lib/dvbt2)> <out.h>

Tables extracted:
  - LDPC parity address tables (dvb_ldpc_bb_impl.cc), normal and short frames,
    DVB-T2 and DVB-S2 rates 1/4 1/3 2/5 1/2 3/5 2/3 3/4 4/5 5/6 8/9 9/10
  - pilot generator: PN sequence, P2 PAPR carriers, continual pilot groups and the
    way init_pilots() combines them for each FFT size / pilot pattern
  - P1: active carriers and S1/S2 patterns
  - frame mapper: L1 padding / puncturing permutations and L1 bit demux
  - bit interleaver column twists and demux tables, frequency interleaver bit permutations
"""
import re
import sys


def read(path):
    with open(path) as f:
        return f.read()


def strip_comments(t):
    t = re.sub(r"/\*.*?\*/", "", t, flags=re.S)
    return re.sub(r"//[^\n]*", "", t)


def array_body(src, name):
    """Return the text between the outer braces of 'X::name[...] = { ... };'."""
    m = re.search(r"::" + re.escape(name) + r"\s*(\[[^\]]*\]\s*)+=\s*\{", src)
    if not m:
        raise KeyError(name)
    i = m.end()
    depth = 1
    j = i
    while depth:
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
        j += 1
    return src[i:j - 1]


def flat(src, name):
    return [int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", array_body(src, name))]


def rows2d(src, name):
    body = array_body(src, name)
    return [[int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", r)] for r in re.findall(r"\{([^{}]*)\}", body)]


def c_array(ctype, name, vals, per_line=16):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per_line):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    base, outp = sys.argv[1], sys.argv[2]
    ldpc = strip_comments(read(base + "/lib/dvb/dvb_ldpc_bb_impl.cc"))
    pg = strip_comments(read(base + "/lib/dvbt2/dvbt2_pilotgenerator_cc_impl.cc"))
    p1 = strip_comments(read(base + "/lib/dvbt2/dvbt2_p1insertion_cc_impl.cc"))
    fm = strip_comments(read(base + "/lib/dvbt2/dvbt2_framemapper_cc_impl.cc"))
    il = strip_comments(read(base + "/lib/dvbt2/dvbt2_interleaver_bb_impl.cc"))
    fi = strip_comments(read(base + "/lib/dvbt2/dvbt2_freqinterleaver_cc_impl.cc"))

    o = ["/* SPDX-License-Identifier: GPL-3.0-or-later",
         " * GENERATED by tools/gen_t2_tables.py from the GNU Radio gr-dtv sources - do not edit.",
         " * Derived from GNU Radio gr-dtv (Copyright Free Software Foundation, Inc. / Ron Economos).",
         " * Define DVBT2_TABLES_LDPC and/or DVBT2_TABLES_T2 before including to get each part. */",
         "#include <stdint.h>", ""]

    # ---------------------------------------------------------------- LDPC
    # (frame 0 normal / 1 short, num, den, variant 0 any / 1 T2 only / 2 S2 only, gr table name)
    codes = [
        (0, 1, 4, 0, "ldpc_tab_1_4N"), (0, 1, 3, 0, "ldpc_tab_1_3N"), (0, 2, 5, 0, "ldpc_tab_2_5N"),
        (0, 1, 2, 0, "ldpc_tab_1_2N"), (0, 3, 5, 0, "ldpc_tab_3_5N"),
        (0, 2, 3, 1, "ldpc_tab_2_3N_DVBT2"), (0, 2, 3, 2, "ldpc_tab_2_3N_DVBS2"),
        (0, 3, 4, 0, "ldpc_tab_3_4N"), (0, 4, 5, 0, "ldpc_tab_4_5N"), (0, 5, 6, 0, "ldpc_tab_5_6N"),
        (0, 8, 9, 0, "ldpc_tab_8_9N"), (0, 9, 10, 0, "ldpc_tab_9_10N"),
        (1, 1, 4, 0, "ldpc_tab_1_4S"), (1, 1, 3, 0, "ldpc_tab_1_3S"), (1, 2, 5, 0, "ldpc_tab_2_5S"),
        (1, 1, 2, 0, "ldpc_tab_1_2S"),
        (1, 3, 5, 1, "ldpc_tab_3_5S_DVBT2"), (1, 3, 5, 2, "ldpc_tab_3_5S_DVBS2"),
        (1, 2, 3, 0, "ldpc_tab_2_3S"), (1, 3, 4, 0, "ldpc_tab_3_4S"), (1, 4, 5, 0, "ldpc_tab_4_5S"),
        (1, 5, 6, 0, "ldpc_tab_5_6S"), (1, 8, 9, 0, "ldpc_tab_8_9S"),
    ]
    o.append("#ifdef DVBT2_TABLES_LDPC")
    o.append("/* each row (group of 360 information bits): count, then 'count' parity addresses */")
    desc = []
    for fr, num, den, var, name in codes:
        rows = rows2d(ldpc, name)
        vals = []
        for r in rows:
            n = r[0]
            assert len(r) >= n + 1, name
            vals += [n] + r[1:1 + n]
        cname = "dvb_" + name.lower()
        o.append(c_array("uint16_t", cname, vals))
        desc.append(f"    {{ {fr}, {num}, {den}, {var}, {len(rows)}, {cname} }},")
    o.append("static const struct dvb_ldpc_code_desc { uint8_t short_frame, num, den, variant; "
             "uint16_t rows; const uint16_t *tab; } dvb_ldpc_codes[] = {")
    o += desc
    o.append("};")
    o.append("#endif /* DVBT2_TABLES_LDPC */\n")

    # ---------------------------------------------------------------- T2
    o.append("#ifdef DVBT2_TABLES_T2")
    # L1 LDPC tables in the frame mapper must equal the generic ones (we reuse the generic encoder)
    for nm in ("ldpc_tab_1_4S", "ldpc_tab_1_2S"):
        a = rows2d(fm, nm)
        b = rows2d(ldpc, nm)
        assert a == b, nm + " differs between framemapper and ldpc"

    o.append(c_array("uint8_t", "t2_pn_sequence_table", flat(pg, "pn_sequence_table")))
    for k in ("1k", "2k", "4k", "8k", "16k", "32k"):
        o.append(c_array("uint16_t", "t2_p2_papr_map_" + k, flat(pg, "p2_papr_map_" + k)))

    # continual pilot groups and their use in init_pilots()
    cp_names = sorted(set(re.findall(r"::(pp\d_(?:cp\d|\d+k))\s*\[", pg)))
    for nm in cp_names:
        o.append(c_array("uint16_t", "t2_" + nm, flat(pg, nm)))
    ip = pg[pg.index("::init_pilots()"):]
    ip = ip[:ip.index("remainder = (i - K_EXT)")]
    uses = []
    fft = None
    pp = None
    pos = 0
    tok = re.compile(r"case FFTSIZE_(\d+)K(?:_T2GI)?:|case PILOT_PP(\d):|for \(int i = 0; i < (\d+); i\+\+\)")
    for m in tok.finditer(ip):
        if m.start() < pos:
            continue
        if m.group(1):
            fft = int(m.group(1))
            continue
        if m.group(2):
            pp = int(m.group(2))
            continue
        cnt = int(m.group(3))
        # body of the loop
        j = ip.index("{", m.end()) + 1
        depth = 1
        k = j
        while depth:
            if ip[k] == "{":
                depth += 1
            elif ip[k] == "}":
                depth -= 1
            k += 1
        body = ip[j:k - 1]
        pos = k
        dm = re.search(r"data_carrier_map\[(\w+)\[i\](?:\s*%\s*(\d+))?\]", body)
        tab, mod = dm.group(1), int(dm.group(2) or 0)
        assert cnt == len(flat(pg, tab)), (tab, cnt)
        miso = 1 if "INVERTED" in body else 0
        before = ip[:m.start()]
        ext = 1 if before.rfind("CARRIERS_EXTENDED") > before.rfind("case PILOT_PP") else 0
        assert ext == (1 if re.search(r"_\d+k$", tab) else 0), tab
        uses.append(f"    {{ {fft}, {pp}, t2_{tab}, {cnt}, {mod}, {miso}, {ext} }},")
    o.append("/* for each FFT size (in K) and pilot pattern: continual pilots at tab[i] % mod (mod 0: no modulo),"
             " miso: gr inverts them for MISO group 2, ext: only in extended carrier mode */")
    o.append("static const struct t2_cp_use { uint8_t fftk, pp; const uint16_t *tab; uint16_t n, mod; "
             "uint8_t miso, ext; } t2_cp_uses[] = {")
    o += uses
    o.append("};")

    o.append(c_array("uint16_t", "t2_p1_active_carriers", flat(p1, "p1_active_carriers")))
    o.append(c_array("uint8_t", "t2_p1_s1_patterns", flat(p1, "s1_modulation_patterns")))
    o.append(c_array("uint8_t", "t2_p1_s2_patterns", flat(p1, "s2_modulation_patterns")))

    for nm in ("pre_puncture", "post_padding_bqpsk", "post_padding_16qam", "post_padding_64qam",
               "post_puncture_bqpsk", "post_puncture_16qam", "post_puncture_64qam"):
        o.append(c_array("uint8_t", "t2_l1_" + nm, flat(fm, nm)))
    o.append(c_array("uint8_t", "t2_l1_mux16", flat(fm, "mux16")))
    o.append(c_array("uint8_t", "t2_l1_mux64", flat(fm, "mux64")))

    for nm in ("twist16n", "twist64n", "twist256n", "twist16s", "twist64s", "twist256s",
               "mux16", "mux64", "mux256", "mux16_35", "mux16_13", "mux16_25", "mux64_35", "mux64_13",
               "mux64_25", "mux256_35", "mux256_23", "mux256s", "mux256s_13", "mux256s_25"):
        o.append(c_array("uint8_t", "t2_bi_" + nm, flat(il, nm)))

    for nm in ("bitperm1keven", "bitperm1kodd", "bitperm2keven", "bitperm2kodd", "bitperm4keven",
               "bitperm4kodd", "bitperm8keven", "bitperm8kodd", "bitperm16keven", "bitperm16kodd", "bitperm32k"):
        o.append(c_array("uint8_t", "t2_fi_" + nm, flat(fi, nm)))
    o.append("#endif /* DVBT2_TABLES_T2 */")

    with open(outp, "w") as f:
        f.write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
